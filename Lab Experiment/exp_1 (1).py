from heapq import heappush, heappop

goal = (1, 2, 3, 4, 5, 6, 7, 8, 0)

def heuristic(state):
    return sum(
        state[i] != 0 and state[i] != goal[i]
        for i in range(9)
    )

def solve(start):
    pq = [(heuristic(start), 0, start, [])]
    visited = set()

    while pq:
        f, g, state, path = heappop(pq)

        if state == goal:
            for step in path + [state]:
                print(step[:3])
                print(step[3:6])
                print(step[6:])
                print()
            return

        if state in visited:
            continue
        visited.add(state)

        zero = state.index(0)
        r, c = divmod(zero, 3)

        for dr, dc in [(0, 1), (0, -1), (1, 0), (-1, 0)]:
            nr, nc = r + dr, c + dc

            if 0 <= nr < 3 and 0 <= nc < 3:
                j = nr * 3 + nc
                new = list(state)
                new[zero], new[j] = new[j], new[zero]
                new = tuple(new)

                if new not in visited:
                    heappush(pq, (
                        g + 1 + heuristic(new),
                        g + 1,
                        new,
                        path + [state]
                    ))

    print("No solution found")

